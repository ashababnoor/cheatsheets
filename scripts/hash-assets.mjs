#!/usr/bin/env node
// Writes _data/asset_versions.yml: a short content hash for each local CSS/JS file.
// The layout appends it as ?v=<hash>, so a file's URL changes only when its content does.
// GitHub Pages can't hash at build time, so run this before committing (the pre-commit hook in .githooks/ does it).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const lines = ['# Generated by scripts/hash-assets.mjs. Do not edit by hand.'];
for (const dir of ['assets/css', 'assets/js']) {
  for (const f of readdirSync(join(root, dir)).sort()) {
    if (!/\.(css|js)$/.test(f)) continue;
    const hash = createHash('sha256').update(readFileSync(join(root, dir, f))).digest('hex').slice(0, 10);
    lines.push(`${f}: "${hash}"`);
  }
}
mkdirSync(join(root, '_data'), { recursive: true });
writeFileSync(join(root, '_data/asset_versions.yml'), lines.join('\n') + '\n');
